"""STAGE 2 — find the model's function with symbolic regression.
The trained model is queried on training inputs; Operon searches for a formula g(features) reproducing the model's output r;
a least-squares polish refits the coefficients (every calendar flag gets a term). Output: formula.txt, formula.py (raw inputs)."""
import numpy as np, sympy as sp, lightgbm as lgb
from pyoperon.sklearn import SymbolicRegressor
from data import load_train
from preprocess import make_inputs, features, INPUTS, FEATURES, FEATURE_CODE

model = lgb.Booster(model_file="model.txt")
df = make_inputs(load_train()).dropna(subset=INPUTS); tr = df[df.date < "2017-01-01"]
rng = np.random.default_rng(0)
F_fit = features(tr[INPUTS].values[rng.choice(len(tr), 30000, replace=False)])
F_chk = features(tr[INPUTS].values[rng.choice(len(tr), 30000, replace=False)])
y_fit, y_chk = model.predict(F_fit), model.predict(F_chk)              # the MODEL's answers are the target
S = [sp.Symbol(n) for n in FEATURES]
fidelity = lambda p: 1 - np.mean((p - y_chk) ** 2) / np.var(y_chk)

# 1) symbolic regression at several formula sizes; keep the best accuracy-vs-size trade-off
best = None
for max_len in (10, 20, 40):
    sr = SymbolicRegressor(allowed_symbols="add,sub,mul,div,constant,variable,square", generations=300, population_size=1500,
                           max_length=max_len, n_threads=4, random_state=0).fit(F_fit, y_fit)
    e = sp.sympify(sr.get_model_string(sr.model_, precision=6).replace("^", "**"), locals={**{f"X{i+1}": s for i, s in enumerate(S)}, "square": lambda q: q**2})
    fid, size = fidelity(sr.predict(F_chk)), sum(1 for _ in sp.preorder_traversal(e))
    print(f"symbolic regression max_len={max_len}: fidelity to model {fid:.4f}, size {size}")
    if best is None or fid - 0.0002 * size > best[0]: best = (fid - 0.0002 * size, fid, e)
_, fid, g = best

# 0/1 flags: flag**k == flag  ->  simplify before polishing
flags = [s for s in S if s.name.startswith(("dow_", "month_"))]
g = g.replace(lambda x: x.is_Pow and x.base in flags and x.exp.is_positive, lambda x: x.base)
# 2) polish: found terms + every calendar flag, coefficients by least squares on the model's output
terms = [t.as_coeff_Mul()[1] for t in (g.args if isinstance(g, sp.Add) else [g]) if not t.is_number]
basis = list(dict.fromkeys([t for t in terms if t not in flags] + flags))
B = lambda F: np.column_stack([np.asarray(sp.lambdify(S, b)(*F.T), float) * np.ones(len(F)) for b in basis] + [np.ones(len(F))])
c, *_ = np.linalg.lstsq(B(F_fit), y_fit, rcond=None)
if fidelity(B(F_chk) @ c) > fid:
    g, fid = sum(sp.Float(float(ci), 4) * b for ci, b in zip(c[:-1], basis)) + sp.Float(float(c[-1]), 4), fidelity(B(F_chk) @ c)
g = g.xreplace({x: sp.Float(float(sp.N(x, 4)), 4) for x in g.atoms(sp.Float)})
print(f"\nFINAL formula (fidelity to model {fid:.4f}):\n  log(1+sales) = log(1+lvl365) + {g}")

# 3) save: readable formula + generated function on raw inputs (preprocessing written in)
open("formula.txt", "w").write(f"log(1+sales) = log(1+lvl365) + {g}\nsales = exp(log(1+sales)) - 1\nfidelity_to_model = {fid:.4f}\n"
                               + "".join(f"{n} = {FEATURE_CODE[n]}\n" for n in FEATURES if sp.Symbol(n) in g.free_symbols))
prep = "\n".join(f"    {n} = {FEATURE_CODE[n]}" for n in FEATURES if sp.Symbol(n) in g.free_symbols)
open("formula.py", "w").write(f'''"""Generated by stage2_symbolic_regression.py — the model's function as a formula (numpy only)."""
import numpy as np

def predict({", ".join(INPUTS)}):
    # preprocessing: inputs -> features
{prep}
    # formula found by symbolic regression
    return np.expm1(np.log1p(lvl365) + {sp.pycode(g).replace("math.", "np.")})
''')
print("saved formula.txt and formula.py")
